            st.warning("**Культура:** Соя ➡️ Покровные культуры (Клевер) ➡️ Кукуруза")
            st.write("**Доказательства NASA:** Снимки Landsat показывают периоды, когда поля остаются голыми (bare-field periods), что вызывает эрозию ветра.")
            st.write("**Преимущества:** Клевер защищает поле в межсезонье, улучшает инфильтрацию воды и борется с вредителями.")
