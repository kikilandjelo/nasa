st.sidebar.header("🎯 Шаг 2: Приоритеты фермера")
priority = st.sidebar.radio("Что для вас важнее всего в этом сезоне?", 
                            ("💧 Максимальная экономия воды", 
                             "🌱 Восстановление органики почвы", 
                             "💰 Максимальная рыночная прибыль"))

st.sidebar.markdown("---")
analyze_btn = st.sidebar.button("🚀 Анализировать данные NASA")

# --- 2. СИМУЛЯЦИЯ ИИ И СЛИЯНИЯ ДАННЫХ (Data Fusion) ---
if analyze_btn:
    with st.spinner('Слияние данных NASA (GPM, SMAP, ECOSTRESS, Landsat)...'):
        import time
        time.sleep(2) # Имитация работы алгоритма
        
        # Аналитика спутниковых метрик
        st.subheader("🛰 Интеграция данных NASA Earth Observations")
