        col1.metric(label="GPM (Осадки за сезон)", value="210 мм", delta="-18% (Аномалия)", delta_color="inverse")
        col2.metric(label="SMAP (Влажность почвы)", value="0.12 м³/м³", delta="Критически низко", delta_color="inverse")
        col3.metric(label="ECOSTRESS (Темп. почвы)", value="32 °C", delta="+2.5 °C (Стресс)", delta_color="inverse")
        col4.metric(label="Landsat (NDVI)", value="0.41", delta="Увядание", delta_color="inverse")

        st.markdown("---")
        st.subheader("🔄 Сравнение стратегий севооборота (Rotation Strategies)")
        st.write("На основе данных NASA и ваших приоритетов, наш ИИ смоделировал 3 сценария (включая вашу текущую практику):")

        # ТАБЛИЦА СРАВНЕНИЯ (Выполняет требование NASA сравнить 3 стратегии)
        tab1, tab2, tab3 = st.tabs(["1. Текущий севооборот (Baseline)", "2. Водосберегающая стратегия (Опция А)", "3. Почвовосстанавливающая (Опция Б)"])
        
        with tab1:
            st.error(f"**Культура:** {current_crop} ➡️ {current_crop} (Монокультура)")
            st.write("**Доказательства NASA:** Данные GRACE и GPM показывают истощение грунтовых вод. Продолжение посадки этой культуры приведет к истощению почвы.")
