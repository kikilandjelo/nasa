        with tab2:
            st.success("**Культура:** Озимая пшеница ➡️ Нут (Chickpea) ➡️ Сорго")
            st.write("**Доказательства NASA:** Модель машинного обучения адаптирована под низкие показатели SMAP (влажности почвы).")
            st.write("**Преимущества:** Нут — азотфиксирующая культура (nitrogen-fixing), сорго обладает глубокими корнями для засухоустойчивости. Идеально при дефиците осадков.")
            st.write("**Риски:** Сорго может иметь более низкую рыночную стоимость в вашем регионе. Требуется оценка местного рынка.")

